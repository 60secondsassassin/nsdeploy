log() {
    printf '%s [INFO ] : %s - %s\n' "$(date +"%G-%m-%d %H:%M:%S")" "${0}" "${*}"
}

error() {
    printf "${RED}%s [ERROR] : %s - %s${NC}\n" "$(date +"%G-%m-%d %H:%M:%S")" "${0}" "${*}" >&2
    exit 1
}
